#!/usr/bin/env node
// Writes src/data/display.hpp: Showdown's display names ("Soft-Boiled",
// "Mr. Mime", "Leftovers") for the engine's species, moves, abilities and
// items, which format.hpp prints. They come from Showdown's own dex, so
// the log's names match Showdown's by construction.
//
//   node tools/display_names.cjs [--showdown PATH] > src/data/display.hpp
//
// Default PATH: showdown/ (built with `node build` there). The engine's IDs
// are read from src/data/names.hpp and the Item enum from items.hpp.
'use strict';
const fs = require('fs');
const path = require('path');

let showdown = path.join(__dirname, '../showdown');
const args = process.argv.slice(2);
if (args[0] === '--showdown' && args[1]) showdown = args[1];
const {Dex} = require(path.join(showdown, 'dist/sim'));
const dex = Dex.mod('gen3');

const data = path.join(__dirname, '../src/data');
const names = fs.readFileSync(path.join(data, 'names.hpp'), 'utf8');
const items = fs.readFileSync(path.join(data, 'items.hpp'), 'utf8');

function ids(array) {
  const m = names.match(new RegExp(array + '\\[[A-Z]+\\] = \\{([\\s\\S]*?)\\n\\};'));
  if (!m) throw new Error(`no ${array} in names.hpp`);
  return [...m[1].matchAll(/"([^"]*)"/g)].map(x => x[1]);
}

// Where the decomp's name isn't Showdown's.
const ALIASES = {smellingsalt: 'smellingsalts'};
// Not in Showdown at all: the decomp's name.
const MISSING = {cacophony: 'Cacophony'};

function name(table, id) {
  if (!id) return '';
  if (table === 'moves' && id.startsWith('hiddenpower')) return 'Hidden Power';
  const x = dex[table].get(ALIASES[id] || id);
  if (x.exists) return x.name;
  // Items with no battle use aren't in Showdown's gen3 dex; the base dex
  // has them.
  const y = Dex[table].get(ALIASES[id] || id);
  if (y.exists) return y.name;
  if (MISSING[id]) return MISSING[id];
  throw new Error(`${table}: no ${id} in Showdown`);
}

function array(cname, type, size, table, list) {
  const lines = list.map(id => `    ${JSON.stringify(name(table, id))},`);
  return `inline constexpr std::string_view ${cname}[${size}] = {\n${lines.join('\n')}\n};\n`;
}

const itemEnum = items.match(/enum class Item : uint8_t \{([\s\S]*?)\n\};/)[1]
  .split('\n').map(s => s.trim().replace(/,$/, '')).filter(Boolean);
const itemNames = itemEnum.map(n => {
  if (['None', 'Mail', 'Other', 'KnockedOff'].includes(n)) return '';
  // Items Showdown doesn't have at all (Exp. Share, Soothe Bell...) can't
  // be in its battles: their split enum name stands in.
  const id = n.toLowerCase();
  if (!dex.items.get(id).exists && !Dex.items.get(id).exists) {
    return n.replace(/([a-z])([A-Z])/g, '$1 $2');
  }
  return name('items', id);
});

process.stdout.write(`// Code generated by \`tools/display_names.cjs\` from Showdown's dex - manual
// edits will be overwritten.

#pragma once

#include <string_view>

#include "abilities.hpp"
#include "items.hpp"
#include "moves.hpp"
#include "species.hpp"

// Showdown's display names, for the log formatter (format.hpp). Indexed
// by enum value; None (and Mail, Other, KnockedOff) is "".
namespace hoenn::display {

${array('SPECIES_NAMES', 'Species', 'SPECIES', 'species', ids('SPECIES_IDS'))}
${array('MOVE_NAMES', 'Move', 'MOVES', 'moves', ids('MOVE_IDS'))}
${array('ABILITY_NAMES', 'Ability', 'ABILITIES', 'abilities', ids('ABILITY_IDS'))}
inline constexpr std::string_view ITEM_NAMES[ITEMS] = {
${itemNames.map(n => `    ${JSON.stringify(n)},`).join('\n')}
};

} // namespace hoenn::display
`);
