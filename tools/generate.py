#!/usr/bin/env python3
"""Generates src/gen3/data/*.hpp from the Emerald decompilation.

Usage: tools/generate.py [path/to/pokeemerald]

Reads only the decomp's C sources and headers. Output is deterministic, so
rerunning it on an unchanged decomp is a no-op. See src/gen3/README.md for the
places where the generated data deliberately differs from the cartridge.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECOMP = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "pokeemerald"
OUT = ROOT / "src" / "gen3" / "data"

HEADER = "// Code generated by `tools/generate.py` - manual edits will be overwritten.\n"


def read(path):
    return (DECOMP / path).read_text()


def pascal(name):
    """MOVE_DOUBLE_SLAP -> DoubleSlap, NIDORAN_F -> NidoranF."""
    return "".join(w.capitalize() for w in name.split("_"))


def defines(path, prefix):
    """Ordered (NAME, value) for `#define PREFIX_NAME <int>` lines."""
    out = []
    for m in re.finditer(rf"^#define {prefix}(\w+)\s+(\d+|0x[0-9A-Fa-f]+)\b", read(path), re.M):
        out.append((m.group(1), int(m.group(2), 0)))
    return out


def blocks(text, key_prefix):
    """{KEY: {field: raw value}} for designated initializers `[PREFIX_KEY] = { .f = v, ... }`."""
    out = {}
    for m in re.finditer(rf"\[{key_prefix}(\w+)\]\s*=\s*\{{[ \t]*\n(.*?)\n\s*\}},?", text, re.S):
        fields = {}
        for f in re.finditer(r"\.(\w+)\s*=\s*(\{[^}]*\}|[^,\n]+)", m.group(2)):
            fields[f.group(1)] = f.group(2).strip()
        out[m.group(1)] = fields
    return out


def emit(name, body):
    path = OUT / name
    path.write_text(HEADER + body)
    print(f"wrote {path.relative_to(ROOT)}")


# Types

TYPES = [(n, v) for n, v in defines("include/constants/pokemon.h", "TYPE_") if n != "NONE"]
assert [v for _, v in TYPES] == list(range(18)), TYPES
TYPE_NAME = {n: ("Mystery" if n == "MYSTERY" else pascal(n)) for n, _ in TYPES}
TYPE_INDEX = {n: v for n, v in TYPES}

MUL = {"TYPE_MUL_NO_EFFECT": "I", "TYPE_MUL_NOT_EFFECTIVE": "R", "TYPE_MUL_SUPER_EFFECTIVE": "S"}


def gen_types():
    text = read("src/battle_main.c")
    table = re.search(r"gTypeEffectiveness\[\d+\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    triples = re.findall(r"(TYPE_\w+),\s*(TYPE_\w+),\s*(TYPE_MUL_\w+)", table)
    chart = [["N"] * 18 for _ in range(18)]
    order = [[255] * 18 for _ in range(18)]
    foresight = False
    for i, (a, d, mul) in enumerate(triples):
        if a == "TYPE_FORESIGHT":
            foresight = True
            continue
        if a == "TYPE_ENDTABLE":
            break
        a, d = TYPE_INDEX[a[5:]], TYPE_INDEX[d[5:]]
        # Entries after the TYPE_FORESIGHT marker are the Ghost immunities that
        # Foresight skips. They're still in the chart; mechanics checks Foresight.
        assert not foresight or (d == TYPE_INDEX["GHOST"] and mul == "TYPE_MUL_NO_EFFECT")
        chart[a][d] = MUL[mul]
        order[a][d] = i

    names = [TYPE_NAME[n] for n, _ in TYPES]
    rows = "\n".join(
        "    {" + ", ".join(chart[a]) + "}, // " + names[a] for a in range(18))
    orders = "\n".join(
        "    {" + ", ".join(f"{o:3d}" for o in order[a]) + "}, // " + names[a] for a in range(18))
    enum = "\n".join(f"  {n}," for n in names)
    emit("types.hpp", f"""
#pragma once

#include <cstdint>

namespace pkmn::gen3 {{

// Cartridge order (include/constants/pokemon.h). Mystery is the ??? type: only
// Curse has it, and it splits physical (below) from special (above).
enum class Type : uint8_t {{
{enum}
}};

inline constexpr uint8_t TYPES = {len(names)};

// The multiplier, in tenths, that ModulateDmgByType applies:
// damage = damage * effectiveness / 10.
enum class Effectiveness : uint8_t {{
  Immune = 0,
  Resisted = 5,
  Neutral = 10,
  Super = 20,
}};

namespace detail {{
using enum Effectiveness;
inline constexpr Effectiveness I = Immune, R = Resisted, N = Neutral, S = Super;

// CHART[attacking][defending], from gTypeEffectiveness in src/battle_main.c.
inline constexpr Effectiveness CHART[TYPES][TYPES] = {{
{rows}
}};

// ORDER[attacking][defending] is the position of that pair's entry in
// gTypeEffectiveness, or 255 for Neutral. Against two types the multipliers are
// applied one entry at a time in table order, flooring after each, so the order
// changes odd damage values. Apply the defender's types in increasing ORDER.
inline constexpr uint8_t ORDER[TYPES][TYPES] = {{
{orders}
}};
}} // namespace detail

constexpr bool is_special(Type t) {{ return t > Type::Mystery; }}

constexpr Effectiveness effectiveness(Type attacking, Type defending) {{
  return detail::CHART[uint8_t(attacking)][uint8_t(defending)];
}}

constexpr uint8_t order(Type attacking, Type defending) {{
  return detail::ORDER[uint8_t(attacking)][uint8_t(defending)];
}}

static_assert(sizeof(Type) == 1);

}} // namespace pkmn::gen3
""")


# Abilities

def gen_abilities():
    abilities = defines("include/constants/abilities.h", "ABILITY_")
    assert [v for _, v in abilities] == list(range(len(abilities)))
    enum = "\n".join(f"  {pascal(n)}," for n, _ in abilities)
    emit("abilities.hpp", f"""
#pragma once

#include <cstdint>

namespace pkmn::gen3 {{

// Cartridge order (include/constants/abilities.h).
enum class Ability : uint8_t {{
{enum}
}};

inline constexpr uint8_t ABILITIES = {len(abilities)};

static_assert(sizeof(Ability) == 1);

}} // namespace pkmn::gen3
""")


# Moves

# Effects that IsTwoTurnsMove (src/battle_script_commands.c) treats as two-turn.
# Sleep Talk can't call these. Bide is on the list.
TWO_TURN = {"SKULL_BASH", "RAZOR_WIND", "SKY_ATTACK", "SOLAR_BEAM", "SEMI_INVULNERABLE", "BIDE"}

TARGETS = [(m[0], 0 if m[1] == "0" else 1 << int(m[2])) for m in re.findall(
    r"^#define MOVE_TARGET_(\w+)\s+(0|\(1 << (\d+)\))", read("include/battle.h"), re.M)]
assert len(TARGETS) == 8, TARGETS


def forbidden_lists():
    """The three prefixes of sMovesForbiddenToCopy, and the Sleep Talk/Assist bans."""
    text = read("src/battle_script_commands.c")
    body = re.search(r"sMovesForbiddenToCopy\[\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    entries = re.findall(r"(MOVE_\w+|MIMIC_FORBIDDEN_END|METRONOME_FORBIDDEN_END)", body)
    mimic = set(entries[: entries.index("MIMIC_FORBIDDEN_END")])
    metronome = set(e for e in entries if e.startswith("MOVE_"))
    # ASSIST_FORBIDDEN_END == METRONOME_FORBIDDEN_END, so Assist reads the same list.
    invalid = re.search(r"IsInvalidForSleepTalkOrAssist\(u16 move\)\s*\{(.*?)\}", text, re.S).group(1)
    sleep_talk_or_assist = set(re.findall(r"MOVE_\w+", invalid)) - {"MOVE_NONE"}
    return mimic, metronome, sleep_talk_or_assist


def gen_moves():
    moves = [(n, v) for n, v in defines("include/constants/moves.h", "MOVE_")
             if n not in ("NONE", "UNAVAILABLE")]
    assert [v for _, v in moves] == list(range(1, len(moves) + 1)), moves[-3:]
    effects = defines("include/constants/battle_move_effects.h", "EFFECT_")
    assert [v for _, v in effects] == list(range(len(effects)))
    data = blocks(read("src/data/battle_moves.h"), "MOVE_")
    mimic, metronome, sleep_talk_or_assist = forbidden_lists()
    target_names = {f"MOVE_TARGET_{n}": pascal(n) for n, _ in TARGETS}

    hp_types = [n for n, _ in TYPES if n not in ("NORMAL", "MYSTERY")]
    rows, enum = [], []
    for name, _ in moves:
        enum.append(pascal(name))
        rows.append((name, pascal(name), data[name], None))
    for t in hp_types:
        enum.append(f"HiddenPower{TYPE_NAME[t]}")
        rows.append(("HIDDEN_POWER", f"HiddenPower{TYPE_NAME[t]}", data["HIDDEN_POWER"], t))

    entries = []
    for cname, ename, d, hp_type in rows:
        move = f"MOVE_{cname}"
        effect = d["effect"][len("EFFECT_"):]
        flags = [f"Flag::{pascal(f[5:])}" for f in re.findall(r"FLAG_\w+", d["flags"])]
        extra = []
        if move in mimic:
            extra.append("Extra::NoMimic")
        if move in metronome:
            extra.append("Extra::NoMetronome")
        if move in metronome or move in sleep_talk_or_assist:
            extra.append("Extra::NoAssist")
        if (move in sleep_talk_or_assist or effect in TWO_TURN
                or move in ("MOVE_FOCUS_PUNCH", "MOVE_UPROAR")):
            extra.append("Extra::NoSleepTalk")
        type_ = TYPE_NAME[hp_type] if hp_type else TYPE_NAME[d["type"][5:]]
        entries.append(
            f"    {{Effect::{pascal(effect)}, {int(d['power'])}, Type::{type_}, "
            f"{int(d['accuracy'])}, {int(d['pp'])}, {int(d['secondaryEffectChance'])}, "
            f"Target::{target_names[d['target']]}, {int(d['priority'])}, "
            f"{' | '.join(flags) or '0'}, {' | '.join(extra) or '0'}}}, // {ename}")

    targets = "\n".join(f"  {pascal(n)} = {v}," for n, v in TARGETS)
    effect_enum = "\n".join(f"  {pascal(n)}," for n, _ in effects)
    move_enum = "\n".join(f"  {n}," for n in enum)
    table = "\n".join(entries)
    emit("moves.hpp", f"""
#pragma once

#include <cstdint>

#include "types.hpp"

namespace pkmn::gen3 {{

// Cartridge order (include/constants/moves.h) for None through PsychoBoost, so
// uint16_t(move) is the decomp's move ID. The 16 typed Hidden Powers follow.
// Their power is per Pokémon. The generic HiddenPower keeps its cartridge slot
// as a stub for computing the type live from IVs, as Emerald does
// (Cmd_hiddenpowercalc). Its data type is meaningless.
enum class Move : uint16_t {{
  None,
{move_enum}
}};

inline constexpr uint16_t MOVES = {len(enum) + 1};
inline constexpr uint16_t CARTRIDGE_MOVES = {len(moves) + 1};

// EFFECT_* from include/constants/battle_move_effects.h, in order.
enum class Effect : uint8_t {{
{effect_enum}
}};

// MOVE_TARGET_* from include/battle.h. These are bit flags in the decomp, but
// every move has exactly one.
enum class Target : uint8_t {{
{targets}
}};

// FLAG_* from include/constants/pokemon.h.
namespace Flag {{
inline constexpr uint8_t MakesContact = 1 << 0;
inline constexpr uint8_t ProtectAffected = 1 << 1;
inline constexpr uint8_t MagicCoatAffected = 1 << 2;
inline constexpr uint8_t SnatchAffected = 1 << 3;
inline constexpr uint8_t MirrorMoveAffected = 1 << 4;
inline constexpr uint8_t KingsRockAffected = 1 << 5;
}} // namespace Flag

// Which calling moves can't pick this move. NoMimic and NoMetronome come from
// sMovesForbiddenToCopy, and NoAssist is that list plus
// IsInvalidForSleepTalkOrAssist. NoSleepTalk is IsInvalidForSleepTalkOrAssist,
// Focus Punch, Uproar and IsTwoTurnsMove (which includes Bide). All are in
// src/battle_script_commands.c.
namespace Extra {{
inline constexpr uint8_t NoMimic = 1 << 0;
inline constexpr uint8_t NoMetronome = 1 << 1;
inline constexpr uint8_t NoAssist = 1 << 2;
inline constexpr uint8_t NoSleepTalk = 1 << 3;
}} // namespace Extra

struct MoveData {{
  Effect effect;
  uint8_t bp;
  Type type;
  uint8_t accuracy;
  uint8_t pp;
  uint8_t chance;
  Target target;
  int8_t priority;
  uint8_t flags;
  uint8_t extra;
}};

static_assert(sizeof(Move) == 2);
static_assert(sizeof(MoveData) == 10);

namespace detail {{
// Indexed by uint16_t(Move) - 1 (None has no entry).
inline constexpr MoveData MOVE_DATA[MOVES - 1] = {{
{table}
}};
}} // namespace detail

constexpr const MoveData &get(Move move) {{ return detail::MOVE_DATA[uint16_t(move) - 1]; }}

constexpr bool is_hidden_power(Move move) {{ return move > Move::PsychoBoost; }}

constexpr Move hidden_power(Type type) {{
  // Gen III Hidden Power types run Fighting..Dark, skipping Normal and Mystery.
  const uint8_t t = uint8_t(type);
  return Move(uint16_t(Move::HiddenPowerFighting) + t - (t > uint8_t(Type::Mystery) ? 2 : 1));
}}

}} // namespace pkmn::gen3
""")


# Species

# Deoxys's stats depend on the cartridge (pokemon.c GetDeoxysStat). The decomp
# has Normal (species_info.h) and Emerald's Speed form (sDeoxysBaseStats).
# Attack and Defense are FireRed/LeafGreen's forms. TODO: check these two against
# pokefirered.
DEOXYS_FORMS = {
    "DeoxysAttack": (50, 180, 20, 150, 180, 20),
    "DeoxysDefense": (50, 70, 160, 90, 70, 160),
    "DeoxysSpeed": None,  # read from sDeoxysBaseStats
}

GENDER = {"MON_MALE": 0, "MON_FEMALE": 254, "MON_GENDERLESS": 255}


def gender_ratio(raw):
    if raw in GENDER:
        return GENDER[raw]
    pct = float(re.fullmatch(r"PERCENT_FEMALE\(([\d.]+)\)", raw).group(1))
    return min(254, int(pct * 255 / 100))


def gen_species():
    text = read("include/constants/pokedex.h")
    national = re.findall(r"^\s+NATIONAL_DEX_(\w+),", text, re.M)
    national = national[national.index("BULBASAUR"): national.index("DEOXYS") + 1]
    info = blocks(read("src/data/pokemon/species_info.h"), "SPECIES_")
    dex = blocks(read("src/data/pokemon/pokedex_entries.h"), "NATIONAL_DEX_")
    deoxys = re.search(r"sDeoxysBaseStats\[\]\s*=\s*\{(.*?)\};", read("src/pokemon.c"), re.S).group(1)
    deoxys = {k: int(v) for k, v in re.findall(r"\[STAT_(\w+)\]\s*=\s*(\d+)", deoxys)}
    DEOXYS_FORMS["DeoxysSpeed"] = tuple(
        deoxys[k] for k in ("HP", "ATK", "DEF", "SPEED", "SPATK", "SPDEF"))

    def abilities(raw):
        a, b = re.findall(r"ABILITY_(\w+)", raw)
        return f"Ability::{pascal(a)}", f"Ability::{pascal(b)}"

    entries, enum = [], []
    for name in national:
        d = info[name]
        stats = tuple(int(d[k]) for k in
                      ("baseHP", "baseAttack", "baseDefense", "baseSpeed", "baseSpAttack", "baseSpDefense"))
        t1, t2 = re.findall(r"TYPE_(\w+)", d["types"])
        a1, a2 = abilities(d["abilities"])
        weight = int(dex[name]["weight"])
        enum.append(pascal(name))
        entries.append((pascal(name), stats, TYPE_NAME[t1], TYPE_NAME[t2], a1, a2,
                        gender_ratio(d["genderRatio"]), weight))
    base = entries[national.index("DEOXYS")]
    for form, stats in DEOXYS_FORMS.items():
        enum.append(form)
        entries.append((form, stats) + base[2:])

    rows = "\n".join(
        f"    {{{{{', '.join(map(str, s))}}}, {{Type::{t1}, Type::{t2}}}, {{{a1}, {a2}}}, "
        f"{g}, {w}}}, // {n}"
        for n, s, t1, t2, a1, a2, g, w in entries)
    species_enum = "\n".join(f"  {n}," for n in enum)
    emit("species.hpp", f"""
#pragma once

#include <cstdint>

#include "abilities.hpp"
#include "types.hpp"

namespace pkmn::gen3 {{

// National Dex order (include/constants/pokedex.h), then the three Deoxys
// forms. This is not the cartridge's internal species order, which puts Hoenn
// in a different order after 25 unused "old Unown" slots.
enum class Species : uint16_t {{
  None,
{species_enum}
}};

inline constexpr uint16_t SPECIES = {len(enum) + 1};

struct BaseStats {{
  uint8_t hp, atk, def, spe, spa, spd;
}};

struct SpeciesData {{
  BaseStats stats;
  Type types[2]; // equal for single-typed species
  Ability abilities[2]; // the second is None when there's only one
  // genderRatio: 0 always male, 254 always female, 255 genderless, otherwise
  // female when the personality's low byte is below it.
  uint8_t gender_ratio;
  uint16_t weight; // hectograms, from the Pokédex entry (Low Kick)
}};

static_assert(sizeof(Species) == 2);

namespace detail {{
// Indexed by uint16_t(Species) - 1 (None has no entry).
inline constexpr SpeciesData SPECIES_DATA[SPECIES - 1] = {{
{rows}
}};
}} // namespace detail

constexpr const SpeciesData &get(Species species) {{
  return detail::SPECIES_DATA[uint16_t(species) - 1];
}}

}} // namespace pkmn::gen3
""")


# Items

def gen_items():
    text = read("include/constants/items.h")
    body = re.search(r"enum\s*\{(.*?)\};", text, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    ids = re.findall(r"\b(ITEM_\w+)\s*(?:=\s*(\w+))?\s*,", body)
    assert ids[0][0] == "ITEM_NONE"
    data = blocks(read("src/data/items.h"), "ITEM_")
    holds = defines("include/constants/hold_effects.h", "HOLD_EFFECT_")
    assert [v for _, v in holds] == list(range(len(holds)))

    held = []
    for name, _ in ids[1:]:
        d = data.get(name[len("ITEM_"):])
        if not d:
            continue
        effect = d.get("holdEffect", "HOLD_EFFECT_NONE")
        # The Enigma Berry has no hold effect on the cartridge (its effect would
        # come from e-Reader data), but it blocks Trick, Thief and Covet like Mail.
        if effect == "HOLD_EFFECT_NONE" and name != "ITEM_ENIGMA_BERRY":
            continue
        param = int(d.get("holdEffectParam", "0"))
        held.append((pascal(name[len("ITEM_"):]), pascal(effect[len("HOLD_EFFECT_"):]), param))
    # Stand-ins for every other holdable item. All Mail behaves the same:
    # Cmd_tryswapitems (Trick) and the Thief/Covet steal check refuse it.
    held.append(("Mail", "None", 0))
    held.append(("Other", "None", 0))
    assert len(held) < 256

    item_enum = "\n".join(f"  {n}," for n, _, _ in held)
    hold_enum = "\n".join(f"  {pascal(n)}," for n, _ in holds)
    rows = "\n".join(f"    {{HoldEffect::{e}, {p}}}, // {n}" for n, e, p in held)
    emit("items.hpp", f"""
#pragma once

#include <cstdint>

namespace pkmn::gen3 {{

// Items with a hold effect (src/data/items.h) plus the Enigma Berry, in
// cartridge order, then two stand-ins. Mail is any of the 12 Mail items, which
// Trick, Thief and Covet can't move (nor the Enigma Berry). Other is any other
// holdable item without a battle effect (balls, evolution stones and so on).
// Those only matter to Trick, Knock Off, Thief and Covet.
enum class Item : uint8_t {{
  None,
{item_enum}
}};

inline constexpr uint8_t ITEMS = {len(held) + 1};

// HOLD_EFFECT_* from include/constants/hold_effects.h, in order.
enum class HoldEffect : uint8_t {{
{hold_enum}
}};

struct ItemData {{
  HoldEffect effect;
  uint8_t param; // holdEffectParam: the percentage, HP or stat it applies to
}};

static_assert(sizeof(Item) == 1);

namespace detail {{
// Indexed by uint8_t(Item) - 1 (None has no entry).
inline constexpr ItemData ITEM_DATA[ITEMS - 1] = {{
{rows}
}};
}} // namespace detail

constexpr const ItemData &get(Item item) {{ return detail::ITEM_DATA[uint8_t(item) - 1]; }}

}} // namespace pkmn::gen3
""")


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    gen_types()
    gen_abilities()
    gen_moves()
    gen_species()
    gen_items()
